-- ManagerW.S — Fase 14: núcleo de billing recurrente
-- Esta migración fue aplicada al esquema privado managerws de Supabase.

ALTER TABLE managerws.subscription
  ADD COLUMN IF NOT EXISTS provider_plan_id varchar(180),
  ADD COLUMN IF NOT EXISTS trial_end timestamp,
  ADD COLUMN IF NOT EXISTS grace_period_end timestamp,
  ADD COLUMN IF NOT EXISTS last_payment_at timestamp,
  ADD COLUMN IF NOT EXISTS last_payment_provider_id varchar(180),
  ADD COLUMN IF NOT EXISTS failed_payment_count integer NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS metadata jsonb NOT NULL DEFAULT '{}'::jsonb;

CREATE INDEX IF NOT EXISTS ix_subscription_org_status_period
  ON managerws.subscription (organization_id, status, current_period_end);
CREATE UNIQUE INDEX IF NOT EXISTS uq_subscription_provider_sub
  ON managerws.subscription (provider, provider_subscription_id)
  WHERE provider_subscription_id IS NOT NULL;

CREATE TABLE IF NOT EXISTS managerws.billing_transaction (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id integer NOT NULL REFERENCES managerws.organization(id),
  subscription_id integer REFERENCES managerws.subscription(id),
  provider varchar(30) NOT NULL,
  provider_transaction_id varchar(180),
  provider_order_id varchar(180),
  provider_event_id varchar(180),
  transaction_type varchar(30) NOT NULL,
  status varchar(30) NOT NULL DEFAULT 'pending',
  amount numeric(14,2) NOT NULL CHECK (amount >= 0),
  currency varchar(10) NOT NULL,
  occurred_at timestamp NOT NULL DEFAULT now(),
  failure_code varchar(120),
  failure_message varchar(500),
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamp NOT NULL DEFAULT now(),
  CONSTRAINT ck_billing_tx_type CHECK (transaction_type IN ('subscription_charge','refund','reversal','adjustment')),
  CONSTRAINT ck_billing_tx_status CHECK (status IN ('pending','completed','failed','refunded','reversed')),
  CONSTRAINT uq_billing_tx_provider_id UNIQUE (provider, provider_transaction_id)
);

CREATE TABLE IF NOT EXISTS managerws.billing_webhook_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider varchar(30) NOT NULL,
  provider_event_id varchar(180) NOT NULL,
  event_type varchar(120) NOT NULL,
  resource_id varchar(180),
  status varchar(20) NOT NULL DEFAULT 'received',
  received_at timestamp NOT NULL DEFAULT now(),
  processed_at timestamp,
  error_message varchar(1000),
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  CONSTRAINT uq_billing_webhook_provider_event UNIQUE (provider, provider_event_id),
  CONSTRAINT ck_billing_webhook_status CHECK (status IN ('received','processed','ignored','failed'))
);

CREATE TABLE IF NOT EXISTS managerws.subscription_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id integer NOT NULL REFERENCES managerws.organization(id),
  subscription_id integer REFERENCES managerws.subscription(id),
  provider varchar(30) NOT NULL,
  event_type varchar(120) NOT NULL,
  provider_event_id varchar(180),
  previous_status varchar(30),
  new_status varchar(30),
  occurred_at timestamp NOT NULL DEFAULT now(),
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  CONSTRAINT uq_subscription_event_provider_event UNIQUE (provider, provider_event_id)
);

CREATE OR REPLACE FUNCTION managerws.reject_billing_history_mutation()
RETURNS trigger LANGUAGE plpgsql
SET search_path = pg_catalog, managerws
AS $$ BEGIN RAISE EXCEPTION 'Billing history is append-only'; END; $$;

DROP TRIGGER IF EXISTS trg_billing_tx_immutable ON managerws.billing_transaction;
CREATE TRIGGER trg_billing_tx_immutable BEFORE UPDATE OR DELETE ON managerws.billing_transaction
FOR EACH ROW EXECUTE FUNCTION managerws.reject_billing_history_mutation();
DROP TRIGGER IF EXISTS trg_subscription_event_immutable ON managerws.subscription_event;
CREATE TRIGGER trg_subscription_event_immutable BEFORE UPDATE OR DELETE ON managerws.subscription_event
FOR EACH ROW EXECUTE FUNCTION managerws.reject_billing_history_mutation();

REVOKE ALL ON TABLE managerws.billing_transaction, managerws.billing_webhook_event, managerws.subscription_event FROM PUBLIC, anon, authenticated;
REVOKE EXECUTE ON FUNCTION managerws.reject_billing_history_mutation() FROM PUBLIC, anon, authenticated;

CREATE INDEX IF NOT EXISTS ix_collection_assignment_org_assigned_by ON managerws.collection_assignment (organization_id, assigned_by);
CREATE INDEX IF NOT EXISTS ix_subscription_event_subscription ON managerws.subscription_event (subscription_id);
