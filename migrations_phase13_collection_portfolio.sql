-- ManagerW.S Phase 13: portfolio, collections, assignments and policy.
-- Applied/verified against Supabase managerws schema.

CREATE TABLE IF NOT EXISTS managerws.collection_assignment (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL,
  credit_id bigint NOT NULL,
  collector_user_id bigint NOT NULL,
  assigned_by bigint NOT NULL,
  active boolean NOT NULL DEFAULT true,
  assigned_at timestamptz NOT NULL DEFAULT now(),
  unassigned_at timestamptz,
  note varchar(500),
  CONSTRAINT fk_assignment_org_credit FOREIGN KEY (organization_id, credit_id)
    REFERENCES managerws.credit (organization_id, id),
  CONSTRAINT fk_assignment_org_collector FOREIGN KEY (organization_id, collector_user_id)
    REFERENCES managerws.membership (organization_id, user_id),
  CONSTRAINT fk_assignment_org_assigner FOREIGN KEY (organization_id, assigned_by)
    REFERENCES managerws.membership (organization_id, user_id),
  CONSTRAINT ck_assignment_dates CHECK ((active AND unassigned_at IS NULL) OR (NOT active AND unassigned_at IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS ix_assignment_org_collector_active ON managerws.collection_assignment (organization_id, collector_user_id, active);
CREATE INDEX IF NOT EXISTS ix_assignment_org_credit_active ON managerws.collection_assignment (organization_id, credit_id, active);
CREATE UNIQUE INDEX IF NOT EXISTS uq_collection_assignment_one_active ON managerws.collection_assignment (organization_id, credit_id) WHERE active;

CREATE TABLE IF NOT EXISTS managerws.collection_policy (
  organization_id bigint PRIMARY KEY REFERENCES managerws.organization(id),
  overdue_1_days integer NOT NULL DEFAULT 1,
  overdue_2_days integer NOT NULL DEFAULT 8,
  overdue_3_days integer NOT NULL DEFAULT 31,
  overdue_4_days integer NOT NULL DEFAULT 61,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ck_collection_policy_order CHECK (overdue_1_days < overdue_2_days AND overdue_2_days < overdue_3_days AND overdue_3_days < overdue_4_days)
);

